package dev.vibecraft.pack;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayDeque;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.CompletionException;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.function.BiConsumer;
import java.util.function.Supplier;
import java.util.regex.Pattern;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.vibecraft.ext.MeshyClient;
import dev.vibecraft.ext.MeshyClient.MeshyException;
import dev.vibecraft.pack.mesh.MeshImport;
import dev.vibecraft.web.ApiExtensions.Reply;

/**
 * Realistic 3D objects generated by Meshy AI text-to-3D:
 * <ul>
 *   <li>{@code POST /api/modules/<id>/models3d} {@code {"path":"assets/<ns>/shapes/<name>","prompt":"...",
 *       "provider":"meshy","size":2,"texture":true,"maxFaces":3000,"resolution":40}} -> {@code 202}
 *       {@code {taskId, status, statusUrl}} (generation takes minutes: preview mesh, then texture);</li>
 *   <li>{@code GET /api/modules/<id>/models3d/<taskId>[?wait=<s>]} -> task status (with {@code wait}, blocks up to
 *       that many seconds, max 55, until the task ends).</li>
 * </ul>
 * When Meshy is done, the OBJ is decimated and its texture baked into per-face colours ({@link MeshImport}),
 * written as {@code <name>.obj} + {@code <name>.mtl} in the module's shapes folder (originals in
 * {@code .vibe/meshy/<name>/}), and the pack is rebuilt: object {@code <ns>:<name>} for {@code Models.spawn}.
 */
public final class Model3dService {

    private static final Pattern PATH = Pattern.compile("assets/([a-z0-9_.-]+)/shapes/((?:[a-z0-9_.-]+/)*)([a-z0-9_-]+)");
    private static final int KEEP = 50;

    private final Supplier<MeshyClient> meshy;
    private final File modulesDir;
    private final Supplier<CompletableFuture<Map<String, Object>>> rebuild;
    private final BiConsumer<String, String> moduleLog;
    private final AtomicInteger seq = new AtomicInteger();
    private final Map<String, Task> tasks = new LinkedHashMap<>();
    private final ArrayDeque<String> order = new ArrayDeque<>();
    private final int maxConcurrent;

    public Model3dService(Supplier<MeshyClient> meshy, File modulesDir, Supplier<CompletableFuture<Map<String, Object>>> rebuild,
                          BiConsumer<String, String> moduleLog, int maxConcurrent) {
        this.meshy = meshy;
        this.modulesDir = modulesDir;
        this.rebuild = rebuild;
        this.moduleLog = moduleLog;
        this.maxConcurrent = Math.max(1, maxConcurrent);
    }

    private static final class Task {
        final String id;
        final String module;
        final String path;
        final String objectId;
        final String prompt;
        final long createdAt = System.currentTimeMillis();
        final CompletableFuture<Void> done = new CompletableFuture<>();
        volatile String status = "PENDING";
        volatile String stage = "en attente de Meshy";
        volatile int progress;
        volatile String error;
        volatile long endedAt;
        volatile Map<String, Object> result;

        Task(String id, String module, String path, String objectId, String prompt) {
            this.id = id;
            this.module = module;
            this.path = path;
            this.objectId = objectId;
            this.prompt = prompt;
        }

        boolean terminal() {
            return status.equals("SUCCEEDED") || status.equals("FAILED");
        }

        Map<String, Object> json() {
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("taskId", id);
            m.put("module", module);
            m.put("path", path);
            m.put("objectId", objectId);
            m.put("prompt", prompt);
            m.put("status", status);
            m.put("stage", stage);
            m.put("progress", progress);
            m.put("error", error);
            m.put("createdAt", createdAt);
            m.put("endedAt", endedAt);
            m.put("statusUrl", "/api/modules/" + module + "/models3d/" + id);
            m.put("result", result);
            return m;
        }
    }

    /** Request options. */
    record Spec(String path, String ns, String folder, String name, String prompt, double size, boolean texture,
                int maxFaces, int resolution, int colors, String texturePrompt) {
    }

    // ================================================================== routes

    public CompletableFuture<Reply> create(String moduleId, String body, String defaultProvider) {
        Spec spec;
        String provider;
        try {
            JsonObject o = parseObject(body);
            provider = str(o, "provider");
            provider = provider == null || provider.isBlank() ? (defaultProvider == null ? "meshy" : defaultProvider)
                    : provider.strip().toLowerCase(Locale.ROOT);
            if (provider.equals("auto")) {
                provider = "meshy";
            }
            spec = parse(o);
        } catch (IllegalArgumentException e) {
            return done(Reply.error(400, e.getMessage()));
        }
        if (!provider.equals("meshy")) {
            return done(Reply.error(400, "\"provider\": seul \"meshy\" sait générer des objets 3D (OpenRouter ne fait que des images) ;"
                    + " sinon décrivez l'objet en .shape.json (ASSETS.md section 9)"));
        }
        File moduleDir = new File(modulesDir, moduleId);
        if (!moduleDir.isDirectory()) {
            return done(Reply.error(404, "unknown module '" + moduleId + "' (create modules/" + moduleId + "/ first)"));
        }
        MeshyClient m = meshy.get();
        if (m == null || !m.hasKey()) {
            return done(Reply.error(503, MeshyClient.NO_KEY + " En attendant, décrivez l'objet en .shape.json (ASSETS.md section 9)."));
        }
        Task t;
        synchronized (this) {
            long running = tasks.values().stream().filter(x -> !x.terminal()).count();
            if (running >= maxConcurrent) {
                return done(Reply.error(429, "déjà " + running + " génération(s) 3D Meshy en cours (max " + maxConcurrent
                        + ") : réessayez quand elles sont finies"));
            }
            t = new Task("m3d-" + seq.incrementAndGet(), moduleId, spec.path(), spec.ns() + ":" + spec.folder() + spec.name(), spec.prompt());
            tasks.put(t.id, t);
            order.addLast(t.id);
            while (order.size() > KEEP) {
                String old = order.peekFirst();
                Task ot = tasks.get(old);
                if (ot != null && !ot.terminal()) {
                    break;
                }
                order.pollFirst();
                tasks.remove(old);
            }
        }
        run(t, m, moduleDir, spec);
        Map<String, Object> r = t.json();
        r.put("next", "génération en cours (plusieurs minutes) : interrogez GET " + r.get("statusUrl") + "?wait=50 jusqu'à \"status\":\"SUCCEEDED\"");
        moduleLog.accept(moduleId, "INFO meshy: 3D task " + t.id + " started for " + spec.path() + ".obj");
        return done(new Reply(202, r));
    }

    public CompletableFuture<Reply> status(String moduleId, String taskId, String waitParam) {
        Task t;
        synchronized (this) {
            t = tasks.get(taskId);
        }
        if (t == null || !t.module.equals(moduleId)) {
            return done(Reply.error(404, "unknown 3D task '" + taskId + "' for module '" + moduleId
                    + "' (tasks are kept in memory: lost if the server restarted)"));
        }
        int wait = 0;
        if (waitParam != null && !waitParam.isBlank()) {
            try {
                wait = Math.max(0, Math.min(55, Integer.parseInt(waitParam.strip())));
            } catch (NumberFormatException e) {
                return done(Reply.error(400, "invalid wait '" + waitParam + "' (seconds, 0..55)"));
            }
        }
        if (wait == 0 || t.terminal()) {
            return done(Reply.ok(t.json()));
        }
        Task tt = t;
        return t.done.copy().completeOnTimeout(null, wait, TimeUnit.SECONDS).handle((v, e) -> Reply.ok(tt.json()));
    }

    /** All tasks (newest first) of a module, or of every module when moduleId is null. */
    public synchronized List<Map<String, Object>> list(String moduleId) {
        return tasks.values().stream().filter(t -> moduleId == null || t.module.equals(moduleId))
                .sorted((a, b) -> Long.compare(b.createdAt, a.createdAt)).map(Task::json).toList();
    }

    // ================================================================== work

    private void run(Task t, MeshyClient m, File moduleDir, Spec spec) {
        t.status = "PREVIEW";
        t.stage = "Meshy génère le maillage";
        MeshyClient.ModelOptions opts = new MeshyClient.ModelOptions(null, 0, spec.texture(), spec.texturePrompt());
        m.textTo3d(spec.prompt(), opts, p -> {
            switch (p.stage()) {
                case "preview" -> {
                    t.status = "PREVIEW";
                    t.stage = "Meshy génère le maillage (" + p.status().toLowerCase(Locale.ROOT) + ")";
                    t.progress = spec.texture() ? p.progress() / 2 : Math.min(95, p.progress());
                }
                case "refine" -> {
                    t.status = "REFINING";
                    t.stage = "Meshy peint la texture (" + p.status().toLowerCase(Locale.ROOT) + ")";
                    t.progress = 50 + p.progress() / 2;
                }
                default -> {
                    t.status = "DOWNLOADING";
                    t.stage = "téléchargement du modèle";
                }
            }
        }).thenAccept(model -> {
            t.status = "CONVERTING";
            t.stage = "conversion en modèle Minecraft";
            t.progress = 99;
            Map<String, Object> res = write(t, moduleDir, spec, model);
            t.result = res;
            rebuild.get().orTimeout(60, TimeUnit.SECONDS).handle((st, err) -> {
                if (st != null && st.get("models") instanceof List<?> models) {
                    for (Object o : models) {
                        if (o instanceof Map<?, ?> d && t.objectId.equals(d.get("id"))) {
                            res.put("compiled", d);
                        }
                    }
                }
                if (!res.containsKey("compiled")) {
                    res.put("compiled", null);
                    res.put("warning", "objet pas encore visible dans GET /api/pack (module désactivé ? erreur dans .vibe/assets.log ?)");
                }
                return null;
            }).whenComplete((v, e) -> end(t, null));
        }).exceptionally(err -> {
            end(t, err);
            return null;
        });
    }

    private void end(Task t, Throwable err) {
        if (err != null) {
            Throwable c = err;
            while ((c instanceof CompletionException) && c.getCause() != null) {
                c = c.getCause();
            }
            t.error = c instanceof MeshyException || c instanceof IllegalArgumentException ? c.getMessage()
                    : c.getClass().getSimpleName() + (c.getMessage() == null ? "" : ": " + c.getMessage());
            t.status = "FAILED";
            t.stage = "échec";
            moduleLog.accept(t.module, "WARNING meshy: 3D task " + t.id + " failed: " + t.error);
        } else {
            t.status = "SUCCEEDED";
            t.stage = "terminé";
            t.progress = 100;
            moduleLog.accept(t.module, "INFO meshy: 3D task " + t.id + " done: " + t.path + ".obj -> " + t.objectId);
        }
        t.endedAt = System.currentTimeMillis();
        t.done.complete(null);
    }

    private Map<String, Object> write(Task t, File moduleDir, Spec spec, MeshyClient.Model model) {
        MeshImport.Result r = MeshImport.convert(model.obj(), model.mtl(), model.texture(), new MeshImport.Options(spec.name(),
                spec.maxFaces(), spec.colors(), spec.size(), spec.resolution(),
                "Generated by Meshy AI for VibeCraft (" + t.id + "): " + spec.prompt().replace('\n', ' ')));
        File shapes = new File(moduleDir, "assets/" + spec.ns() + "/shapes/" + spec.folder());
        File objF = new File(shapes, spec.name() + ".obj");
        File mtlF = new File(shapes, spec.name() + ".mtl");
        try {
            Path root = moduleDir.getCanonicalFile().toPath().resolve("assets");
            if (!objF.getCanonicalFile().toPath().startsWith(root)) {
                throw new IllegalArgumentException("path escapes the module's assets folder");
            }
            Files.createDirectories(shapes.toPath());
            // mtl first: the pack poller must never see the obj without its materials
            atomic(mtlF, r.mtl().getBytes(StandardCharsets.UTF_8));
            atomic(objF, r.obj().getBytes(StandardCharsets.UTF_8));
            File keep = new File(moduleDir, ".vibe/meshy/" + spec.ns() + "_" + spec.folder().replace('/', '_') + spec.name());
            Files.createDirectories(keep.toPath());
            Files.write(new File(keep, "meshy.obj").toPath(), model.obj());
            if (model.mtl() != null) {
                Files.write(new File(keep, "meshy.mtl").toPath(), model.mtl());
            }
            if (model.texture() != null) {
                Files.write(new File(keep, "texture_base_color.png").toPath(), model.texture());
            }
        } catch (IOException e) {
            throw new CompletionException(new IOException("écriture impossible : " + e.getMessage()));
        }
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("objectId", t.objectId);
        m.put("files", List.of(spec.path() + ".obj", spec.path() + ".mtl"));
        m.put("meshyFaces", r.inFaces());
        m.put("faces", r.outFaces());
        m.put("colors", r.colors());
        m.put("textured", r.textured());
        m.put("previewTaskId", model.previewTaskId());
        m.put("refineTaskId", model.refineTaskId());
        File shape = new File(shapes, spec.name() + ".shape.json");
        if (shape.exists()) {
            m.put("warning", spec.name() + ".shape.json defines the same object: delete it");
        }
        m.put("next", "placez-le avec Models.spawn(ctx, \"" + t.objectId + "\", loc, 1.0) ; aperçu : .vibe/previews/"
                + PackService.previewName(t.objectId));
        return m;
    }

    private static void atomic(File f, byte[] data) throws IOException {
        Path tmp = new File(f.getParentFile(), "." + f.getName() + ".tmp").toPath();
        Files.write(tmp, data);
        try {
            Files.move(tmp, f.toPath(), StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        } catch (IOException e) {
            Files.move(tmp, f.toPath(), StandardCopyOption.REPLACE_EXISTING);
        }
    }

    // ================================================================== parsing

    static JsonObject parseObject(String body) {
        try {
            JsonElement el = JsonParser.parseString(body == null || body.isBlank() ? "{}" : body);
            if (!el.isJsonObject()) {
                throw new IllegalArgumentException("body must be a JSON object");
            }
            return el.getAsJsonObject();
        } catch (com.google.gson.JsonParseException e) {
            throw new IllegalArgumentException("invalid JSON body: " + PackBuilder.jsonMessage(e)
                    + " (tip: put the JSON in a file and use curl --data-binary @file.json)");
        }
    }

    static Spec parse(JsonObject o) {
        String path = str(o, "path");
        if (path == null || path.isBlank()) {
            throw new IllegalArgumentException("missing \"path\", e.g. \"assets/<namespace>/shapes/<name>\"");
        }
        path = path.strip().replace('\\', '/');
        if (path.endsWith(".obj")) {
            path = path.substring(0, path.length() - 4);
        }
        var mt = PATH.matcher(path);
        if (path.contains("..") || path.contains("//") || !mt.matches()) {
            throw new IllegalArgumentException("\"path\" must look like assets/<namespace>/shapes/<name> (lowercase a-z 0-9 _ - .): " + path);
        }
        String prompt = str(o, "prompt");
        if (prompt == null || prompt.isBlank()) {
            throw new IllegalArgumentException("missing \"prompt\" (the object to generate, in English, e.g. \"a red vintage sports car\")");
        }
        if (prompt.length() > 800) {
            throw new IllegalArgumentException("\"prompt\" too long (max 800 chars)");
        }
        double size = num(o, "size", 2);
        if (size <= 0 || size > 64) {
            throw new IllegalArgumentException("\"size\" (largest dimension in blocks) must be between 0 and 64");
        }
        int maxFaces = (int) num(o, "maxFaces", 3000);
        if (maxFaces < 200 || maxFaces > 20000) {
            throw new IllegalArgumentException("\"maxFaces\" must be between 200 and 20000");
        }
        int resolution = (int) num(o, "resolution", 40);
        if (resolution < 8 || resolution > 96) {
            throw new IllegalArgumentException("\"resolution\" (voxel grid) must be between 8 and 96");
        }
        int colors = (int) num(o, "colors", 32);
        if (colors < 2 || colors > 64) {
            throw new IllegalArgumentException("\"colors\" must be between 2 and 64");
        }
        boolean texture = !o.has("texture") || !o.get("texture").isJsonPrimitive() || o.get("texture").getAsBoolean();
        String tp = str(o, "texturePrompt");
        return new Spec(path, mt.group(1), mt.group(2), mt.group(3), prompt.strip(), size, texture, maxFaces, resolution, colors, tp);
    }

    private static String str(JsonObject o, String k) {
        JsonElement e = o.get(k);
        return e != null && e.isJsonPrimitive() ? e.getAsString() : null;
    }

    private static double num(JsonObject o, String k, double def) {
        JsonElement e = o.get(k);
        if (e == null || e.isJsonNull()) {
            return def;
        }
        try {
            return e.getAsDouble();
        } catch (RuntimeException ex) {
            throw new IllegalArgumentException("\"" + k + "\" must be a number");
        }
    }

    private static CompletableFuture<Reply> done(Reply r) {
        return CompletableFuture.completedFuture(r);
    }
}
